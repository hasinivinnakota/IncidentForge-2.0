def print_header(title: str) -> None:
    width = 72
    print()
    print("=" * width)
    print(f"  {title}")
    print("=" * width)


def print_disclaimer() -> None:
    print_header("DISCLAIMERS")
    print("""
  [!] This evaluation uses 100% SYNTHETIC data generated by this script.
  [!] Results do NOT represent real-world SOC detection performance.
  [!] The production model was NOT retrained or modified.
  [!] Ground-truth labels are assigned by the data generator, not by
      human SOC analysts or real incident outcomes.
  [!] Perfect or near-perfect metrics on synthetic data should NOT be
      interpreted as evidence of production-ready accuracy.
""")


def print_class_distribution(
    label: str, labels: list[str], classes: list[str],
) -> None:
    counts = Counter(labels)
    total = len(labels)
    print(f"\n  {label} class distribution ({total} samples):")
    print(f"  {'Class':<12} {'Count':>7} {'Ratio':>8}")
    print(f"  {'-'*12} {'-'*7} {'-'*8}")
    for cls in classes:
        c = counts.get(cls, 0)
        ratio = c / total if total > 0 else 0.0
        print(f"  {cls:<12} {c:>7} {ratio:>7.1%}")


def print_binary_results(metrics: dict[str, Any]) -> None:
    print_header("BINARY CLASSIFICATION (benign vs attack)")
    print(f"""
  Binary mapping: low/medium -> benign (0), high/critical -> attack (1)

  Accuracy:   {metrics['accuracy']:.4f}
  Precision:  {metrics['precision']:.4f}
  Recall:     {metrics['recall']:.4f}
  F1-Score:   {metrics['f1']:.4f}

  Confusion Matrix:
                  Predicted
                  Neg    Pos
  Actual Neg   {metrics['confusion_matrix']['TN']:>5}  {metrics['confusion_matrix']['FP']:>5}
  Actual Pos   {metrics['confusion_matrix']['FN']:>5}  {metrics['confusion_matrix']['TP']:>5}
""")


def print_multiclass_results(metrics: dict[str, Any], classes: list[str]) -> None:
    print_header("4-CLASS RISK LEVEL CLASSIFICATION")
    print(f"""
  Risk levels: low (0-24), medium (25-49), high (50-74), critical (75-100)

  Overall Accuracy:   {metrics['accuracy']:.4f}
  Macro Precision:    {metrics['macro_precision']:.4f}
  Macro Recall:       {metrics['macro_recall']:.4f}
  Macro F1-Score:     {metrics['macro_f1']:.4f}
""")

    # Per-class table
    print(f"  {'Class':<12} {'Precision':>10} {'Recall':>10} {'F1':>10} {'Support':>10}")
    print(f"  {'-'*12} {'-'*10} {'-'*10} {'-'*10} {'-'*10}")
    for cls in classes:
        m = metrics["per_class"][cls]
        print(f"  {cls:<12} {m['precision']:>10.4f} {m['recall']:>10.4f} {m['f1']:>10.4f} {m['support']:>10}")

    # Confusion matrix
    print(f"\n  Confusion Matrix (rows=actual, cols=predicted):")
    print(f"  {'':>12}", end="")
    for cls in classes:
        print(f" {cls:>10}", end="")
    print()
    print(f"  {'':>12}", end="")
    for _ in classes:
        print(f" {'-'*10}", end="")
    print()
    cm = metrics["confusion_matrix"]
    for actual in classes:
        print(f"  {actual:>12}", end="")
        for pred in classes:
            print(f" {cm[actual][pred]:>10}", end="")
        print()


def print_imbalance_analysis(
    test_labels: list[str], classes: list[str],
) -> None:
    print_header("CLASS IMBALANCE ANALYSIS")
    counts = Counter(test_labels)
    total = len(test_labels)
    max_count = max(counts.values())
    min_count = min(counts.values())
    ratio = max_count / min_count if min_count > 0 else float("inf")

    print(f"""
  Test set size:          {total}
  Most frequent class:    {max(counts, key=counts.get)} ({max_count} samples)
  Least frequent class:   {min(counts, key=counts.get)} ({min_count} samples)
  Imbalance ratio:        {ratio:.2f}:1
""")
    if ratio > 2.0:
        print("  [!] Moderate class imbalance detected. Macro-averaged metrics give")
        print("      equal weight to each class regardless of support. Per-class")
        print("      metrics should be examined individually for minority classes.")
    else:
        print("  [OK] Class distribution is reasonably balanced (ratio < 2:1).")
        print("     Both macro and weighted metrics are meaningful.")
    print()


