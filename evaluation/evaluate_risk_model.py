def generate_evaluation_dataset(
    n_samples: int = N_SAMPLES,
    seed: int = SEED,
) -> tuple[list[dict[str, float]], list[str], list[int]]:
    """Generate labeled synthetic incidents for evaluation.

    Returns:
        features_list: List of feature dicts (one per sample)
        risk_labels:   Ground-truth 4-class labels (low/medium/high/critical)
        binary_labels: Ground-truth binary labels (0=benign, 1=attack)

    NOTE: This data is SYNTHETIC. It exercises all 23 v2.0 features with
    controlled noise and class overlap so that the evaluation is informative
    (unlike the existing train.py data which is trivially separable).
    """
    rng = random.Random(seed)

    # Determine per-class sample counts
    class_counts: dict[str, int] = {}
    remaining = n_samples
    for i, (cls, ratio) in enumerate(CLASS_DISTRIBUTION.items()):
        if i == len(CLASS_DISTRIBUTION) - 1:
            class_counts[cls] = remaining
        else:
            count = int(round(ratio * n_samples))
            class_counts[cls] = count
            remaining -= count

    features_list: list[dict[str, float]] = []
    risk_labels: list[str] = []
    binary_labels: list[int] = []

    for cls, count in class_counts.items():
        for _ in range(count):
            features = _generate_sample(cls, rng)
            features_list.append(features)
            risk_labels.append(cls)
            binary_labels.append(BINARY_MAP[cls])

    # Shuffle all data deterministically
    indices = list(range(len(features_list)))
    rng.shuffle(indices)
    features_list = [features_list[i] for i in indices]
    risk_labels = [risk_labels[i] for i in indices]
    binary_labels = [binary_labels[i] for i in indices]

    return features_list, risk_labels, binary_labels


