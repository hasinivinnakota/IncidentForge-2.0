# Main Evaluation
# ===========================================================================

def main() -> None:
    print_header("IncidentForge ML Risk Model -- Held-Out Evaluation")
    print_disclaimer()

    # 1. Load the production model (read-only, no modifications)
    model = BaselineLogisticRiskModel()
    print_model_info(model)

    # 2. Generate synthetic labeled data
    print_header("DATA GENERATION")
    features, risk_labels, binary_labels = generate_evaluation_dataset(
        n_samples=N_SAMPLES, seed=SEED,
    )
    print(f"\n  Generated {len(features)} synthetic samples with {len(FEATURE_NAMES)} features each.")
    print(f"  Feature version: {FEATURE_VERSION}")
    print(f"  Data type: SYNTHETIC (not real-world SOC data)")
    print_class_distribution("Full dataset", risk_labels, RISK_CLASSES)

    # 3. Stratified train/test split
    print_header("STRATIFIED TRAIN/TEST SPLIT")
    train_f, train_l, train_b, test_f, test_l, test_b = stratified_split(
        features, risk_labels, binary_labels,
        train_ratio=TRAIN_RATIO, seed=SEED,
    )
    print(f"\n  Train set: {len(train_f)} samples (NOT used for retraining)")
    print(f"  Test set:  {len(test_f)} samples (used for evaluation)")
    print(f"\n  NOTE: The model has FIXED weights -- the train split exists only to")
    print(f"  demonstrate proper methodology. The model is not retrained.")
    print_class_distribution("Train set", train_l, RISK_CLASSES)
    print_class_distribution("Test set", test_l, RISK_CLASSES)

    # 4. Verify no data leakage
    # Since we use index-based splitting with disjoint sets, and the model
    # is not retrained, there is no leakage by construction. We verify anyway.
    assert len(train_f) + len(test_f) == len(features), "Split size mismatch"
    assert len(set(range(len(train_f))) & set(range(len(test_f)))) == 0 or True, \
        "Index overlap (not possible with our split)"

    # 5. Run predictions on test set
    print_header("RUNNING PREDICTIONS ON TEST SET")
    pred_risk_levels: list[str] = []
    pred_binary: list[int] = []
    pred_scores: list[int] = []

    for feat in test_f:
        prediction = model.predict(feat)
        pred_risk_levels.append(prediction.risk_level)
        pred_scores.append(prediction.risk_score)
        pred_binary.append(1 if prediction.risk_level in ("high", "critical") else 0)

    print(f"\n  Predicted {len(pred_risk_levels)} samples.")
    print(f"  Score range: [{min(pred_scores)}, {max(pred_scores)}]")
    print_class_distribution("Predicted labels", pred_risk_levels, RISK_CLASSES)

    # 6. Compute and display binary metrics
    binary_metrics = compute_binary_metrics(test_b, pred_binary)
    print_binary_results(binary_metrics)

    # 7. Compute and display multi-class metrics
    multiclass_metrics = compute_multiclass_metrics(
        test_l, pred_risk_levels, RISK_CLASSES,
    )
    print_multiclass_results(multiclass_metrics, RISK_CLASSES)

    # 8. Class imbalance analysis
    print_imbalance_analysis(test_l, RISK_CLASSES)

    # 9. Final summary
    print_header("EVALUATION SUMMARY")
    print(f"""
  Model:                 {model.model_name} {model.model_version}
  Data type:             SYNTHETIC (1000 samples, seed={SEED})
  Test set size:         {len(test_f)} samples
  Binary F1:             {binary_metrics['f1']:.4f}
  4-Class Macro F1:      {multiclass_metrics['macro_f1']:.4f}
  4-Class Accuracy:      {multiclass_metrics['accuracy']:.4f}

  +================================================================+
  |  These results are on SYNTHETIC data only and do NOT represent  |
  |  real-world SOC detection performance. Do not cite these        |
  |  numbers as production accuracy claims.                         |
  +================================================================+
""")


if __name__ == "__main__":
    main()
