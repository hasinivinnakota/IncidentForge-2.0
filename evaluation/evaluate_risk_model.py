# Stratified Train/Test Split (pure Python)
# ===========================================================================

def stratified_split(
    features: list[dict[str, float]],
    labels: list[str],
    binary_labels: list[int],
    train_ratio: float = TRAIN_RATIO,
    seed: int = SEED,
) -> tuple[
    list[dict[str, float]], list[str], list[int],  # train
    list[dict[str, float]], list[str], list[int],   # test
]:
    """Split data with stratification on 4-class labels.

    Ensures each class has proportional representation in train and test sets.
    Prevents data leakage: train and test are disjoint index sets.
    """
    rng = random.Random(seed + 7)  # Different seed from generation

    # Group indices by class
    class_indices: dict[str, list[int]] = defaultdict(list)
    for i, label in enumerate(labels):
        class_indices[label].append(i)

    train_idx: list[int] = []
    test_idx: list[int] = []

    for cls in RISK_CLASSES:
        indices = class_indices[cls][:]
        rng.shuffle(indices)
        n_train = int(round(len(indices) * train_ratio))
        train_idx.extend(indices[:n_train])
        test_idx.extend(indices[n_train:])

    # Shuffle within train and test
    rng.shuffle(train_idx)
    rng.shuffle(test_idx)

    train_f = [features[i] for i in train_idx]
    train_l = [labels[i] for i in train_idx]
    train_b = [binary_labels[i] for i in train_idx]
    test_f = [features[i] for i in test_idx]
    test_l = [labels[i] for i in test_idx]
    test_b = [binary_labels[i] for i in test_idx]

    return train_f, train_l, train_b, test_f, test_l, test_b


