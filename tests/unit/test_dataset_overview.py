import pytest
from fastapi.testclient import TestClient

from backend.app.main import app

def test_dataset_overview_not_found():
    client = TestClient(app)
    response = client.get("/api/v1/data-assets/invalid_id/overview")
    assert response.status_code == 404

def test_dataset_overview_integration(api_client):
    # 1. Profile a valid dataset
    upload_data = {
        "dataset_id": "test_ds_123",
        "name": "test_dataset",
        "format": "csv",
        "file_path": "/tmp/test.csv",
        "size_bytes": 1000,
        "record_count": 50,
        "column_count": 5,
        "columns": [
            {"name": "id", "data_type": "int", "is_sensitive": False},
            {"name": "email", "data_type": "string", "is_sensitive": True, "pii_type": "email", "sensitivity": "MEDIUM"}
        ],
        "sensitive_columns": ["email"],
        "sensitivity": "MEDIUM"
    }
    
    res = api_client.post("/api/v1/data-assets", json=upload_data)
    assert res.status_code == 201
    asset_id = res.json()["dataset_id"]
    
    # 2. Simulate activity
    sim_res = api_client.post(f"/api/v1/data-assets/{asset_id}/simulate")
    assert sim_res.status_code == 202
    
    # 3. Get Overview
    overview_res = api_client.get(f"/api/v1/data-assets/{asset_id}/overview")
    assert overview_res.status_code == 200
    
    data = overview_res.json()
    assert data["dataset_id"] == asset_id
    assert data["asset"]["dataset_id"] == asset_id
    
    # We should have some alerts generated by the simulation
    assert len(data["alerts"]) > 0
    assert len(data["activities"]) > 0
    assert len(data["incidents"]) > 0
